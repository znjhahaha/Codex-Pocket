function Get-PocketIdentityAcl([string]$Path,[bool]$IsDirectory) {
    Assert-PocketPlainPath $Path
    $item = Get-Item -LiteralPath $Path -Force
    if ($item.PSIsContainer -ne $IsDirectory) { throw 'Identity storage has the wrong file/directory type.' }
    if (-not $IsDirectory) {
        if (-not ('PocketIdentityFileInfo' -as [type])) {
            Add-Type -TypeDefinition @'
using System;
using System.ComponentModel;
using System.IO;
using System.Runtime.InteropServices;
using Microsoft.Win32.SafeHandles;
public static class PocketIdentityFileInfo {
    [StructLayout(LayoutKind.Sequential)]
    private struct Information {
        public uint Attributes;
        public System.Runtime.InteropServices.ComTypes.FILETIME Created, Accessed, Written;
        public uint Volume, SizeHigh, SizeLow, Links, IndexHigh, IndexLow;
    }
    [DllImport("kernel32.dll", SetLastError=true)]
    private static extern bool GetFileInformationByHandle(SafeFileHandle handle, out Information information);
    public static bool IsRegularUnlinkedFile(string path) {
        using (var file = File.Open(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite)) {
            Information info;
            if (!GetFileInformationByHandle(file.SafeFileHandle, out info)) throw new Win32Exception(Marshal.GetLastWin32Error());
            return (info.Attributes & (0x400u | 0x10u)) == 0 && info.Links == 1;
        }
    }
}
'@
        }
        if (-not [PocketIdentityFileInfo]::IsRegularUnlinkedFile($Path)) { throw 'Identity storage must be a regular unlinked file.' }
    }
    $acl = Get-Acl -LiteralPath $Path
    $descriptor = [Security.AccessControl.RawSecurityDescriptor]::new($acl.GetSecurityDescriptorBinaryForm(),0)
    $user = [Security.Principal.WindowsIdentity]::GetCurrent().User
    $valid = $null -ne $descriptor.Owner -and $descriptor.Owner.Equals($user) -and
        ($descriptor.ControlFlags -band [Security.AccessControl.ControlFlags]::DiscretionaryAclProtected) -ne 0 -and
        $null -ne $descriptor.DiscretionaryAcl -and $descriptor.DiscretionaryAcl.Count -eq 1
    if ($valid) {
        $ace = $descriptor.DiscretionaryAcl[0]
        $valid = $ace -is [Security.AccessControl.CommonAce] -and
            $ace.AceType -eq [Security.AccessControl.AceType]::AccessAllowed -and
            $ace.AceFlags -eq [Security.AccessControl.AceFlags]::None -and
            $ace.AccessMask -eq [int][Security.AccessControl.FileSystemRights]::FullControl -and
            $ace.SecurityIdentifier.Equals($user)
    }
    if (-not $valid) { throw 'Identity ACL requires current-user owner, protected DACL and exactly one FullControl user allow ACE with no inheritance flags.' }
    return $acl
}
function Set-PocketCopiedIdentityAcl([string]$Path,$SourceAcl,[bool]$IsDirectory) {
    # Only used on newly copied staging objects. Never repairs an existing identity.
    $copy = if ($IsDirectory) { [Security.AccessControl.DirectorySecurity]::new() } else { [Security.AccessControl.FileSecurity]::new() }
    $copy.SetSecurityDescriptorBinaryForm($SourceAcl.GetSecurityDescriptorBinaryForm(),[Security.AccessControl.AccessControlSections]'Owner,Access')
    Set-Acl -LiteralPath $Path -AclObject $copy
    Get-PocketIdentityAcl $Path $IsDirectory | Out-Null
}
function Assert-PocketInitializedState([string]$Directory) {
    foreach ($name in @('config.json','identity\certificate.der','identity\private-key.der')) {
        $path = Join-Path $Directory $name
        Assert-PocketPlainPath $path
        if (-not [IO.File]::Exists($path) -or (Get-Item -LiteralPath $path).Length -eq 0) {
            throw 'An initialized state directory with its existing identity is required; no identity is generated by this installer.'
        }
    }
    try { $config = Get-Content -LiteralPath (Join-Path $Directory 'config.json') -Raw -Encoding UTF8 | ConvertFrom-Json }
    catch { throw 'Invalid initialized state configuration (contents omitted).' }
    if ($config.protocol -ne 1) { throw 'Unsupported initialized state protocol.' }
    Get-PocketIdentityAcl (Join-Path $Directory 'identity') $true | Out-Null
    foreach ($name in @('certificate.der','private-key.der','identity.lock')) {
        Get-PocketIdentityAcl (Join-Path $Directory ('identity\' + $name)) $false | Out-Null
    }
}
function Initialize-PocketPrivateState([string]$Agent,[string]$Directory) {
    & $Agent init --state $Directory --gateway-bind '127.0.0.1:17892' --json | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Fresh private state initialization failed; staged state retained.' }
}
function Copy-PocketState([string]$Source, [string]$Destination) {
    # Never merge identities. Lock the source helper's durable state while copying.
    $Source = Get-PocketDirectoryPath $Source
    $Destination = Get-PocketDirectoryPath $Destination
    Assert-PocketLocalPath $Source
    Assert-PocketLocalPath $Destination
    Assert-PocketPlainPath $Destination
    if (Test-Path -LiteralPath $Destination) { throw 'Migration destination must be absent; never merge identities.' }
    if (($Destination + '\').StartsWith($Source + '\',[StringComparison]::OrdinalIgnoreCase)) { throw 'State migration paths cannot overlap.' }
    Assert-PocketInitializedState $Source
    $identityNames = @('certificate.der','private-key.der','identity.lock')
    $identityAcls = @{}
    $identityHashes = @{}
    $identityAcls['directory'] = Get-PocketIdentityAcl (Join-Path $Source 'identity') $true
    foreach ($name in $identityNames) {
        $path = Join-Path $Source ('identity\' + $name)
        $identityAcls[$name] = Get-PocketIdentityAcl $path $false
        $identityHashes[$name] = Get-PocketFileHash $path
    }
    $lockPath = Join-Path $Source 'agent.lock'
    Assert-PocketPlainPath $lockPath
    $lock = [IO.File]::Open($lockPath,[IO.FileMode]::OpenOrCreate,[IO.FileAccess]::ReadWrite,[IO.FileShare]::ReadWrite)
    $locked = $false
    $stage = $Destination + '.migration-' + [guid]::NewGuid().ToString('N')
    try {
        try { $lock.Lock(0,[long]::MaxValue); $locked = $true }
        catch { throw 'State migration requires the source helper to be stopped by its owner.' }
        Assert-PocketPlainPath $stage
        [void][IO.Directory]::CreateDirectory($stage)
        $sid = [Security.Principal.WindowsIdentity]::GetCurrent().User
        $acl = [Security.AccessControl.DirectorySecurity]::new()
        $acl.SetOwner($sid)
        $acl.SetAccessRuleProtection($true,$false)
        foreach ($identity in @($sid,[Security.Principal.SecurityIdentifier]::new('S-1-5-18'))) {
            $acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new($identity,'FullControl','ContainerInherit,ObjectInherit','None','Allow'))
        }
        Set-Acl -LiteralPath $stage -AclObject $acl
        $queue = [Collections.Generic.Queue[string]]::new()
        $queue.Enqueue($Source)
        while ($queue.Count) {
            foreach ($item in Get-ChildItem -LiteralPath $queue.Dequeue() -Force) {
                Assert-PocketPlainPath $item.FullName
                if ($item.FullName -eq $lockPath) { continue }
                $relative = $item.FullName.Substring($Source.TrimEnd('\','/').Length + 1)
                $target = Join-Path $stage $relative
                if ($item.PSIsContainer) { [void][IO.Directory]::CreateDirectory($target); $queue.Enqueue($item.FullName) }
                else { [IO.File]::Copy($item.FullName,$target,$false) }
            }
        }
        # Files must be protected FIRST: protecting the parent with no inheritable
        # ACE would otherwise strip the children's inherited access before Set-Acl.
        foreach ($name in $identityNames) {
            Set-PocketCopiedIdentityAcl (Join-Path $stage ('identity\' + $name)) $identityAcls[$name] $false
        }
        Set-PocketCopiedIdentityAcl (Join-Path $stage 'identity') $identityAcls['directory'] $true
        foreach ($name in $identityNames) {
            if ((Get-PocketFileHash (Join-Path $stage ('identity\' + $name))) -ne $identityHashes[$name] -or
                (Get-PocketFileHash (Join-Path $Source ('identity\' + $name))) -ne $identityHashes[$name]) {
                throw 'Identity bytes changed during state migration (contents omitted).'
            }
        }
        Assert-PocketInitializedState $Source
        Assert-PocketInitializedState $stage
        Assert-PocketPlainPath $Destination
        if (Test-Path -LiteralPath $Destination) { throw 'State destination appeared during migration.' }
        if ([IO.Path]::GetDirectoryName($stage) -ne [IO.Path]::GetDirectoryName($Destination)) { throw 'Invalid migration target.' }
        Move-PocketStagedDirectory $stage $Destination
    } finally {
        if ($locked) { $lock.Unlock(0,[long]::MaxValue) }
        $lock.Dispose()
        # Failed copies retain their private staging directory for owner recovery.
    }
}
. (Join-Path $PSScriptRoot 'windows-startup.ps1')

function New-PocketShortcutBytes([string]$Temporary,[string]$Launcher,[string]$Mode) {
    $shell = New-Object -ComObject WScript.Shell
    $link = $null
    try {
        $link=$shell.CreateShortcut($Temporary); $link.TargetPath=$Launcher; $link.Arguments=$Mode
        $link.WorkingDirectory=[IO.Path]::GetDirectoryName($Launcher); $link.WindowStyle=7; $link.Save()
        return ,([IO.File]::ReadAllBytes($Temporary))
    } finally {
        if ($link) { [void][Runtime.InteropServices.Marshal]::FinalReleaseComObject($link) }
        [void][Runtime.InteropServices.Marshal]::FinalReleaseComObject($shell)
        if ([IO.File]::Exists($Temporary)) { [IO.File]::Delete($Temporary) }
    }
}
function Get-PocketBackup([string]$Path) {
    $hash = Get-PocketFileHash $Path
    return @{path=$Path;hash=$hash;bytes=$(if($hash){[Convert]::ToBase64String([IO.File]::ReadAllBytes($Path))}else{$null})}
}
function Assert-PocketBackup($Backup) {
    if ($null -eq $Backup.bytes) { if ($null -ne $Backup.hash) { throw 'Invalid backup integrity.' }; return }
    if ((Get-PocketBytesHash ([Convert]::FromBase64String($Backup.bytes))) -ne $Backup.hash) { throw 'Backup integrity check failed.' }
}
function Write-PocketBackup($Backup) {
    Assert-PocketBackup $Backup
    Assert-PocketPlainPath $Backup.path
    if ($null -eq $Backup.bytes) { if ([IO.File]::Exists($Backup.path)) { [IO.File]::Delete($Backup.path) } }
    else { [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($Backup.path)); Write-PocketAtomic $Backup.path ([Convert]::FromBase64String($Backup.bytes)) }
}
function Get-PocketIntegrationSnapshot([string]$Manifest,[string[]]$Links) {
    return @{manifest=(Get-PocketBackup $Manifest);links=@($Links|ForEach-Object{Get-PocketBackup $_});cli=(Get-PocketUserCliPath);cliKind=(Get-PocketUserCliKind);task=(Get-PocketTaskXml)}
}
function Get-PocketProperty($Value,[string]$Name,$Fallback) {
    if($Value -is [Collections.IDictionary]) { if($Value.Contains($Name)){return $Value[$Name]} }
    elseif($null -ne $Value -and $Value.PSObject.Properties[$Name]) { return $Value.$Name }
    return $Fallback
}
function Save-PocketRollbackSnapshot($Snapshot,[string]$InstallRoot) {
    Assert-PocketBackup $Snapshot.manifest
    $hash=$Snapshot.manifest.hash
    if ($hash -notmatch '^[a-f0-9]{64}$') { throw 'Invalid rollback record hash.' }
    $directory=Join-Path $InstallRoot 'rollback'
    Assert-PocketUnredirectedPath $directory
    [void][IO.Directory]::CreateDirectory($directory)
    $path=Join-Path $directory ($hash+'.json')
    Assert-PocketUnredirectedPath $path
    if ([IO.File]::Exists($path)) {
        if ((Get-PocketFileHash $path) -ne $hash) { throw 'Rollback archive integrity failed.' }
    } else { Write-PocketAtomic $path ([Convert]::FromBase64String($Snapshot.manifest.bytes)) }
    # Never embed the preceding installation recursively: the stable bootstrap
    # intentionally bounds its current record to 1 MiB.
    return @{manifest=@{path=$Snapshot.manifest.path;hash=$hash;bytes=$null;archiveFile=$hash+'.json'};links=$Snapshot.links;cli=$Snapshot.cli;cliKind=$Snapshot.cliKind;task=$Snapshot.task}
}
function Read-PocketRollbackSnapshot($Snapshot,[string]$InstallRoot) {
    $archive=Get-PocketProperty $Snapshot.manifest 'archiveFile' $null
    if ($null -eq $archive) { return $Snapshot } # Existing inline records remain readable.
    if ($archive -cne ($Snapshot.manifest.hash+'.json') -or $archive -cnotmatch '^[a-f0-9]{64}\.json$' -or $null -ne $Snapshot.manifest.bytes) { throw 'Invalid rollback archive reference.' }
    $path=Join-Path (Join-Path $InstallRoot 'rollback') $archive
    Assert-PocketUnredirectedPath $path
    if ((Get-Item -LiteralPath $path).Length -gt 64MB) { throw 'Rollback archive exceeds limit.' }
    $backup=Get-PocketBackup $path
    if ($backup.hash -ne $Snapshot.manifest.hash) { throw 'Rollback archive integrity failed.' }
    return @{manifest=@{path=$Snapshot.manifest.path;hash=$backup.hash;bytes=$backup.bytes};links=$Snapshot.links;cli=$Snapshot.cli;cliKind=(Get-PocketProperty $Snapshot 'cliKind' 'String');task=$Snapshot.task}
}
function Assert-PocketSnapshot($Snapshot,[string]$Manifest,[string[]]$Links) {
    if ($Snapshot.manifest.path -ne $Manifest -or $Snapshot.links.Count -ne $Links.Count) { throw 'Invalid recovery record path.' }
    Assert-PocketBackup $Snapshot.manifest
    if((Get-PocketProperty $Snapshot 'cliKind' 'String') -notin @('String','ExpandString')) { throw 'Invalid recovery environment kind.' }
    for($i=0;$i -lt $Links.Count;$i++) {
        if ($Snapshot.links[$i].path -ne $Links[$i]) { throw 'Invalid recovery shortcut record path.' }
        Assert-PocketBackup $Snapshot.links[$i]
    }
}
function Restore-PocketTransaction($Journal,[string]$Manifest,[string[]]$Links,[string]$Launcher) {
    Assert-PocketSnapshot $Journal.before $Manifest $Links
    Assert-PocketSnapshot $Journal.after $Manifest $Links
    $cli=Get-PocketUserCliPath
    if ($cli -ne $Journal.before.cli -and $cli -ne $Journal.after.cli) { throw 'Environment drift during recovery.' }
    $kind=Get-PocketUserCliKind
    $beforeKind=Get-PocketProperty $Journal.before 'cliKind' 'String'
    $afterKind=Get-PocketProperty $Journal.after 'cliKind' 'String'
    if ($kind -ne $beforeKind -and $kind -ne $afterKind) { throw 'Environment kind drift during recovery.' }
    foreach($i in 0..($Links.Count-1)) {
        $hash=Get-PocketFileHash $Links[$i]
        if ($hash -ne $Journal.before.links[$i].hash -and $hash -ne $Journal.after.links[$i].hash) { throw 'Shortcut drift during recovery.' }
    }
    $hash=Get-PocketFileHash $Manifest
    if ($hash -ne $Journal.before.manifest.hash -and $hash -ne $Journal.after.manifest.hash) { throw 'Installation record drift during recovery.' }
    $task=Get-PocketTaskXml
    if (-not (Test-PocketTaskEquivalent $task $Journal.before.task) -and -not (Test-PocketTaskEquivalent $task $Journal.after.task)) { throw 'Scheduled task drift during recovery.' }
    if ($task -ne $Journal.before.task) { Set-PocketTaskXml $Journal.before.task }
    foreach($backup in $Journal.before.links) { Write-PocketBackup $backup }
    if ($cli -ne $Journal.before.cli -or $kind -ne $beforeKind) { Set-PocketUserCliPath $Journal.before.cli $beforeKind; Send-PocketEnvironmentChanged }
    Write-PocketBackup $Journal.before.manifest
}
function Invoke-PocketWindowsInstall {
    [CmdletBinding()]
    param([string]$SourceDirectory,[string]$StateDirectory,[string]$ExistingStateDirectory,[switch]$Apply,[switch]$Uninstall,[switch]$Rollback,[switch]$Initialize,[hashtable]$Context,
        [ValidateSet('Preserve','Enable','Disable')][string]$UiStartup='Preserve')
    $ErrorActionPreference='Stop'
    if ($Uninstall -and $Rollback) { throw 'Choose uninstall or rollback.' }
    if (-not $Context) { $Context=@{InstallRoot=(Join-Path (Get-PocketLocalAppData) 'CodexPocket');Programs=[Environment]::GetFolderPath('Programs');Startup=[Environment]::GetFolderPath('Startup')} }
    $installRoot=Get-PocketDirectoryPath $Context.InstallRoot
    Assert-PocketLocalPath $installRoot
    Assert-PocketUnredirectedPath $installRoot -ProbeWrite:$Apply
    Assert-PocketUnredirectedPath $Context.Programs -ProbeWrite:$Apply
    Assert-PocketUnredirectedPath $Context.Startup -ProbeWrite:$Apply
    $launcher=Join-Path $installRoot 'pocket-launcher.exe'
    $manifestPath=Join-Path $installRoot 'desktop-install.json'
    $journalPath=Join-Path $installRoot 'installation-pending.json'
    $links=@((Join-Path $Context.Programs 'Codex Pocket.lnk'),(Join-Path $Context.Programs 'Codex Pocket Desktop.lnk'),(Join-Path $Context.Startup 'Codex Pocket.lnk'))
    foreach($path in @($manifestPath,$journalPath,$launcher)+$links) { Assert-PocketPlainPath $path }
    $mutex=$null; $owns=$false
    try {
        if ($Apply) {
            $mutex=[Threading.Mutex]::new($false,('Local\CodexPocketInstall_'+(Get-PocketBytesHash ([Text.Encoding]::UTF8.GetBytes($installRoot.ToLowerInvariant())))))
            try { $owns=$mutex.WaitOne(0) } catch [Threading.AbandonedMutexException] { $owns=$true }
            if (-not $owns) { throw 'Another installer owns this integration directory.' }
        }
        if ([IO.File]::Exists($journalPath)) {
            if (-not $Apply) { throw 'Interrupted installation requires -Apply to recover before a new plan.' }
            $journal=Get-Content -LiteralPath $journalPath -Raw -Encoding UTF8 | ConvertFrom-Json
            Restore-PocketTransaction $journal $manifestPath $links $launcher
            [IO.File]::Delete($journalPath)
        }
        $before=Get-PocketIntegrationSnapshot $manifestPath $links
        $saved=$null
        if ($before.manifest.bytes) {
            $saved=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($before.manifest.bytes)) | ConvertFrom-Json
            if ($saved.version -notin @(2,3) -or $saved.installRoot -ne $installRoot -or $saved.shortcuts.Count -ne 3 -or $saved.generation -notmatch '^[a-f0-9]{64}$') { throw 'Unsupported installation record.' }
            $expected=if($saved.version -eq 2){Join-Path $installRoot ('bin\'+$saved.generation+'\pocket-bridge.exe')}else{$launcher}
            if ($saved.bridge -ne $expected) { throw 'Invalid installation record path.' }
            if ($before.cli -ne $saved.bridge -and $before.cli -ne $saved.previousCliPath) { throw 'CODEX_CLI_PATH changed outside this installer; refusing drift.' }
            for($i=0;$i -lt 3;$i++) {
                $entry=$saved.shortcuts[$i]
                if ($entry.path -ne $links[$i]) { throw 'Invalid shortcut record path.' }
                foreach($kind in @('original','installed')) { Assert-PocketBackup @{bytes=$entry.$kind;hash=$entry.($kind+'Hash')} }
                if ($before.links[$i].hash -ne $entry.originalHash -and $before.links[$i].hash -ne $entry.installedHash) { throw 'Shortcut changed outside this installer; refusing drift.' }
            }
            if ($saved.version -eq 3 -and (Get-PocketFileHash $launcher) -ne $saved.launcherHash) { throw 'Stable launcher integrity check failed.' }
            if ((Get-PocketProperty $saved 'previousCliKind' 'String') -notin @('String','ExpandString')) { throw 'Invalid original environment kind.' }
        }
        Assert-PocketTaskOwned $before.task $launcher
        if (($Uninstall -or $Rollback) -and -not $saved) { return @{action='restore';applied=$false;installed=$false} }
        if ($Rollback -and ($saved.version -ne 3 -or -not $saved.rollback)) { throw 'No previous installation available for rollback.' }
        if (-not ($Uninstall -or $Rollback)) {
            Assert-PocketWindowsPrerequisites
            $SourceDirectory=Get-PocketDirectoryPath $SourceDirectory
            $release=Test-PocketWindowsDirectory $SourceDirectory
            $releaseHash=Get-PocketFileHash (Join-Path $SourceDirectory 'windows-manifest.json')
            $generation=$releaseHash
            if (-not $StateDirectory) { $StateDirectory=if($saved){$saved.stateDirectory}else{Join-Path $installRoot 'agent'} }
            $StateDirectory=Get-PocketDirectoryPath $StateDirectory; Assert-PocketPlainPath $StateDirectory
            Assert-PocketLocalPath $StateDirectory
            if ($saved -and $StateDirectory -ne $saved.stateDirectory) { throw 'Restore the existing installation before changing its state directory.' }
            $migrate=-not [IO.File]::Exists((Join-Path $StateDirectory 'config.json'))
            $fresh=$migrate -and $Initialize -and -not $ExistingStateDirectory
            if ($fresh) {
                if ($saved -or (Test-Path -LiteralPath $StateDirectory)) { throw 'Fresh initialization requires an absent state directory and no existing installation.' }
            } elseif ($migrate) {
                if (-not $ExistingStateDirectory) { throw 'An initialized state directory with its existing identity is required.' }
                $ExistingStateDirectory=Get-PocketDirectoryPath $ExistingStateDirectory
                Assert-PocketLocalPath $ExistingStateDirectory
                Assert-PocketInitializedState $ExistingStateDirectory
                if (Test-Path -LiteralPath $StateDirectory) { throw 'Migration destination must be absent; never merge identities.' }
                if (($StateDirectory+'\').StartsWith($ExistingStateDirectory+'\',[StringComparison]::OrdinalIgnoreCase)) { throw 'State migration paths cannot overlap.' }
            } else { Assert-PocketInitializedState $StateDirectory }
            if (($StateDirectory+'\').StartsWith((Join-Path $installRoot 'bin')+'\',[StringComparison]::OrdinalIgnoreCase)) { throw 'State must be outside the installed binary directory.' }
            $package=Get-PocketDesktopPackage
            if (-not [IO.File]::Exists((Join-Path $package.InstallLocation 'app\resources\codex.exe'))) { throw 'Original desktop runtime is missing.' }
            $bin=Join-Path $installRoot ('bin\'+$generation)
        }
        $plan=@{action=$(if($Uninstall){'uninstall'}elseif($Rollback){'rollback'}else{'install'});applied=[bool]$Apply;installRoot=$installRoot;stateDirectory=$(if($saved){$saved.stateDirectory}else{$StateDirectory});processesStarted=0;processesStopped=0;shortcuts=$links;scheduledTask=(Get-PocketTaskName)}
        if (-not $Apply) { return $plan }
        [void][IO.Directory]::CreateDirectory($installRoot)
        if ($Rollback) {
            $after=Read-PocketRollbackSnapshot $saved.rollback $installRoot
            Assert-PocketSnapshot $after $manifestPath $links
        } elseif ($Uninstall) {
            $after=@{manifest=$before.manifest;cli=$saved.previousCliPath;cliKind=(Get-PocketProperty $saved 'previousCliKind' 'String');task=$(if($saved.version -eq 3){$saved.previousTask}else{$null});links=@()}
            foreach($entry in $saved.shortcuts) { $after.links+=@{path=$entry.path;bytes=$entry.original;hash=$entry.originalHash} }
        } else {
            if ($fresh) {
                $freshStage=$StateDirectory+'.staging-'+[guid]::NewGuid().ToString('N')
                Initialize-PocketPrivateState (Join-Path $SourceDirectory 'pocket-agent.exe') $freshStage
                $plan.processesStarted=1
                Assert-PocketInitializedState $freshStage
                Move-PocketStagedDirectory $freshStage $StateDirectory
            } elseif ($migrate) { Copy-PocketState $ExistingStateDirectory $StateDirectory }
            Assert-PocketPlainPath $bin
            if (-not [IO.Directory]::Exists($bin)) {
                [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($bin))
                $stage=$bin+'.staging-'+[guid]::NewGuid().ToString('N'); [void][IO.Directory]::CreateDirectory($stage)
                foreach($name in @((Get-PocketWindowsFiles))+@('windows-manifest.json')) { [IO.File]::Copy((Join-Path $SourceDirectory $name),(Join-Path $stage $name),$false) }
                Test-PocketWindowsDirectory $stage | Out-Null
                if ((Get-PocketFileHash (Join-Path $stage 'windows-manifest.json')) -ne $releaseHash) { throw 'Staged manifest hash does not match the planned generation.' }
                Move-PocketStagedDirectory $stage $bin
            }
            Test-PocketWindowsDirectory $bin | Out-Null
            if ((Get-PocketFileHash (Join-Path $bin 'windows-manifest.json')) -ne $releaseHash) { throw 'Installed manifest hash does not match the planned generation.' }
            # The bootstrap ABI stays stable across deliveries. Never replace an in-use bootstrap.
            if (-not [IO.File]::Exists($launcher)) { Write-PocketAtomic $launcher ([IO.File]::ReadAllBytes((Join-Path $bin 'pocket-launcher.exe'))) }
            elseif (-not $saved -and (Get-PocketFileHash $launcher) -ne (Get-PocketFileHash (Join-Path $bin 'pocket-launcher.exe'))) { throw 'Unmanaged stable launcher exists.' }
            $savedUi=$saved -and $saved.version -eq 3 -and $null -ne $saved.shortcuts[2].installed
            $uiEnabled=$false # The scheduled supervisor now also owns background tray startup.
            $startupUnchanged=$UiStartup -eq 'Preserve' -or ((Test-PocketTaskLogon $before.task) -eq ($UiStartup -eq 'Enable'))
            $unchanged=$startupUnchanged -and $saved -and $saved.version -eq 3 -and $saved.generation -eq $generation -and $savedUi -eq $uiEnabled -and ([Convert]::FromBase64String($before.manifest.bytes)).Length -lt 1MB
            if ($unchanged) { $candidate=$saved }
            else {
                $entries=@()
                for($i=0;$i -lt 3;$i++) {
                    $original=if($saved){$saved.shortcuts[$i].original}else{$before.links[$i].bytes}
                    $originalHash=if($saved){$saved.shortcuts[$i].originalHash}else{$before.links[$i].hash}
                    $bytes=if($i -eq 2 -and -not $uiEnabled){$null}else{New-PocketShortcutBytes (Join-Path $installRoot ([guid]::NewGuid().ToString('N')+'.lnk')) $launcher $(if($i -eq 1){'--pocket-desktop'}else{'--pocket-ui'})}
                    $entries+=@{path=$links[$i];original=$original;originalHash=$originalHash;installed=$(if($null -ne $bytes){[Convert]::ToBase64String($bytes)}else{$null});installedHash=$(if($null -ne $bytes){Get-PocketBytesHash $bytes}else{$null})}
                }
                $candidate=[ordered]@{version=3;installRoot=$installRoot;generation=$generation;releaseHash=$releaseHash;bridge=$launcher;launcherHash=(Get-PocketFileHash $launcher);stateDirectory=$StateDirectory;previousCliPath=$(if($saved){$saved.previousCliPath}else{$before.cli});previousCliKind=$(if($saved){Get-PocketProperty $saved 'previousCliKind' 'String'}else{$before.cliKind});previousTask=$(if($saved -and $saved.version -eq 3){$saved.previousTask}else{$before.task});shortcuts=$entries;rollback=$(if($saved){Save-PocketRollbackSnapshot $before $installRoot}else{$null})}
                if ($saved) {
                    $archive=Join-Path $installRoot ('desktop-install.'+$saved.generation+'.json')
                    if (-not [IO.File]::Exists($archive)) { Write-PocketAtomic $archive ([Convert]::FromBase64String($before.manifest.bytes)) }
                }
            }
            $recordBytes=[Text.UTF8Encoding]::new($false).GetBytes(($candidate|ConvertTo-Json -Depth 30))
            # Preserve the exact record on an idempotent apply.
            $recordBackup=if($unchanged){$before.manifest}else{@{path=$manifestPath;bytes=[Convert]::ToBase64String($recordBytes);hash=(Get-PocketBytesHash $recordBytes)}}
            $logon=if($UiStartup -eq 'Enable'){$true}elseif($UiStartup -eq 'Disable'){$false}elseif($null -ne $before.task){Test-PocketTaskLogon $before.task}else{$true}
            $after=@{manifest=$recordBackup;cli=$launcher;cliKind='String';task=$(if($null -ne $before.task -and (Test-PocketTaskLogon $before.task) -eq $logon){$before.task}else{New-PocketTaskXml $launcher $logon});links=@()}
            foreach($entry in $candidate.shortcuts) { $after.links+=@{path=$entry.path;bytes=$entry.installed;hash=$entry.installedHash} }
        }
        $journal=@{before=$before;after=$after}
        Write-PocketJson $journalPath $journal
        try {
            foreach($backup in $after.links) { if ((Get-PocketFileHash $backup.path) -ne $backup.hash) { Write-PocketBackup $backup } }
            if ((Get-PocketUserCliPath) -ne $before.cli -or (Get-PocketUserCliKind) -ne $before.cliKind) { throw 'Environment changed during integration.' }
            $afterKind=Get-PocketProperty $after 'cliKind' 'String'
            if ($before.cli -ne $after.cli -or $before.cliKind -ne $afterKind) { Set-PocketUserCliPath $after.cli $afterKind; Send-PocketEnvironmentChanged }
            if ((Get-PocketTaskXml) -ne $before.task) { throw 'Scheduled task changed during integration.' }
            if ($before.task -ne $after.task) { Set-PocketTaskXml $after.task }
            Write-PocketBackup $after.manifest
            [IO.File]::Delete($journalPath)
        } catch {
            $failure=$_
            try { Restore-PocketTransaction $journal $manifestPath $links $launcher; [IO.File]::Delete($journalPath) }
            catch { Write-Warning 'Recovery is incomplete. Private journal retained; retry -Apply after resolving the locked or changed integration.' }
            throw $failure
        }
        return $plan
    } finally { if($owns){$mutex.ReleaseMutex()}; if($mutex){$mutex.Dispose()} }
}
